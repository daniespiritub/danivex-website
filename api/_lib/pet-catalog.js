export function petSpeciesName(id) {
  const k = String(id || '').replace(/[^0-9]/g, '')
  return PET_SPECIES[k] || ''
}

export function petSkinName(id) {
  const k = String(id || '').replace(/[^0-9]/g, '')
  return PET_SKINS[k] || ''
}

// resolvePet(petInfo) — resolver GENERAL de mascota. Separa ESPECIE (petId -> catalogo),
// APODO del jugador (petInfo.name), y ASPECTO (skinId -> catalogo). NUNCA devuelve el id
// numerico como nombre: si la especie es desconocida y el name de la API es numerico o
// vacio, `name` queda '' (la UI muestra "Mascota desconocida", conservando el id).
export function resolvePet(petInfo) {
  const p = petInfo || {}
  const id = p.id != null ? String(p.id) : ''
  const skinId = p.skinId != null ? String(p.skinId) : ''
  const species = petSpeciesName(id)
  const skinName = petSkinName(skinId)
  const raw = String(p.name || '').trim()
  const rawIsName = raw && !/^\d+$/.test(raw) // el name de la API a veces es el id numerico
  const nickname = rawIsName && raw !== species ? raw : ''
  const name = species || (rawIsName ? raw : '')
  return {
    id,
    name, // especie (o apodo no-numerico); '' si desconocida (nunca el id)
    nickname,
    level: p.level != null ? String(p.level) : '',
    exp: p.exp != null ? String(p.exp) : '',
    skinId,
    skinName,
    skillId: p.selectedSkillId != null ? String(p.selectedSkillId) : '',
    nameSource: species ? 'itemdata' : (name ? 'api-name' : ''),
    skinSource: skinName ? 'itemdata' : '',
  }
}
